def is_pictograph(ch: str) -> bool:
    """True if character is a standalone pictograph (象形文字)."""
    return ch in PICTOGRAPHS


def get_pictograph_info(ch: str) -> dict:
    """Return pictograph evolution stages and child-friendly explanation."""
    if ch in PICTOGRAPHS:
        return PICTOGRAPHS[ch]
    if ch in _KANGXI:
        info = get_radical_info(ch)
        icon = info.get("icon", "🔤")
        name = info.get("name", ch)
        return {
            "icon": icon,
            "name": name,
            "type": "象形文字 / 獨體部首",
            "explanation": f"「{ch}」是古代的圖畫象形字，是一個獨立完整的部首，不能再分拆成兩半喔！",
            "stages": [
                {"label": "實物圖畫", "icon": icon, "desc": f"古代人照著「{name}」的樣子畫出圖畫"},
                {"label": "現代漢字", "char": ch, "desc": f"演變為現代漢字「{ch}」！"}
            ]
        }
    return {}


def get_radical_info(rad: str) -> dict:
    """Return dictionary with name, meaning, icon, and domain for a radical or component."""
    if not rad:
        return {"name": "", "meaning": "", "domain": "", "icon": "🔤"}
    icon = RADICAL_ICONS.get(rad) or RADICAL_ICONS.get(_VARIANT.get(rad, ""), "🔤")
    if rad in RADICAL_INFO:
        info = dict(RADICAL_INFO[rad])
        info["icon"] = icon
        return info
    base = _VARIANT.get(rad, "")
    if base and base in RADICAL_INFO:
        info = dict(RADICAL_INFO[base])
        info["icon"] = icon
        return info
    if rad in _KANGXI:
        return {"name": f"{rad}部", "meaning": f"表示與「{rad}」事物或性質有關", "domain": f"{rad}類", "icon": icon}
    return {"name": rad, "meaning": "", "domain": "", "icon": icon}


def get_component_info(comp: str) -> dict:
    """Return component name and descriptive role."""
    if not comp:
        return {"name": "", "meaning": "", "domain": ""}
    return get_radical_info(comp)


def get_char_story(ch: str, radical: str = "", phonetic: str = "", components=None, root_idc: str = "") -> str:
    """Deterministic structural and semantic story connecting components -> character -> meaning."""
    if ch in CHAR_STORY:
        return CHAR_STORY[ch]

    components = components or []
    rad_info = get_radical_info(radical) if radical else {}
    rad_name = rad_info.get("name", radical)
    rad_mean = rad_info.get("meaning", "")

    # Clean two-part phonogram with clear radical and phonetic
    if radical and phonetic and phonetic != "無" and len(phonetic) == 1:
        phon_hint = f"聲旁「{phonetic}」提供讀音線索"
        if rad_mean:
            return f"「{ch}」：部首「{radical}」（{rad_name}）{rad_mean}；{phon_hint}。"
        return f"「{ch}」：由形旁「{radical}」表意，{phon_hint}。"

    # Ideographic / multi-component character
    if len(components) >= 2:
        parts_desc = []
        for c in components:
            c_info = get_radical_info(c)
            c_name = c_info.get("name") or c
            if c_info.get("meaning"):
                parts_desc.append(f"「{c}」（{c_name}：{c_info['meaning']}）")
            else:
                parts_desc.append(f"「{c}」")
        return f"「{ch}」：由{' 與 '.join(parts_desc)}組合表意。"

    # Single radical or basic glyph
    if radical and rad_mean:
        return f"「{ch}」：屬「{rad_name}」，{rad_mean}。"

    return f"「{ch}」：常用中文小學字詞。"



def _load():
    idx = {}
    if not os.path.exists(_DATA):
        return idx
    with open(_DATA, encoding="utf-8") as fh:
        for line in fh:
            if not line or line.startswith("#"):
                continue
            parts = line.rstrip("\n").split("\t")
            if len(parts) >= 2 and len(parts[0]) == 1:
                # strip region tags ([GJK]…) and keep the first IDS variant
                ids = _TAG_RE.sub("", parts[1]).split()[0] if parts[1].strip() else ""
                if ids:
                    idx[parts[0]] = ids
    return idx


def _load_freq():
    """char -> frequency rank (1 = most common). Absent chars are treated as very rare
    so confusable suggestions skew toward glyphs a P4 child has actually met."""
    path = os.path.join(_HERE, "assets", "char-freq.txt")
    rank = {}
    if not os.path.exists(path):
        return rank
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            if not line or line.startswith("#"):
                continue
            parts = line.rstrip("\n").split("\t")
            if len(parts) == 2 and parts[1].isdigit():
                rank[parts[0]] = int(parts[1])
    return rank


