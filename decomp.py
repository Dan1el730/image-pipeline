# Simplified-only components. A confusable whose IDS contains one of these is a
# simplified glyph that leaked in via the OpenSubtitles frequency source — drop it,
# this is a Traditional-Chinese product. (Deterministic; no opencc dependency.)
_SIMP_MARKERS = set("讠马贝车钅纟饣门见页风鸟龙鱼长鸡鸟韦专东软轮")
# Common simplified-ONLY whole characters that carry no simplified radical marker, so
# the marker test alone misses them (华 for 華, 节 for 節…). Curated to exclude any
# glyph still valid in Traditional (里/后/吃/床/群 are NOT here — they are dual-use).
_SIMP_CHARS = set(
    "华东书长乐买卖龙业丽习写农关兴单丰专区历应庆击节协罗层张来时实学觉师将义乡严举丧两个为乌乔产亲亿仓众优会"
)


def _is_simplified(ch):
    if ch in _SIMP_CHARS:
        return True
    ids = _IDS.get(ch, ch)
    return any(c in _SIMP_MARKERS or c in _SIMP_CHARS for c in ids)


# Stroke / placeholder fragments that are NOT meaningful 部件 — they appear when the
# IDS over-decomposes a glyph down to strokes (慶 → 广 コ 丨 丨 乛) or uses a CHISE
# placeholder for an unencoded component (華 → 艹 ⑦). Dropped from decomposition.
_STROKES = set("丨丶丿乛亅乚乀乁")
# Real component chars live in CJK main, ext-A, the radical blocks, and ext-B (𠂊, the
# top of 負/爭, is a legitimate ext-B component — so ext-B is NOT blanket-junk).
_GOOD_RANGES = ((0x4E00, 0x9FFF), (0x3400, 0x4DBF), (0x2E80, 0x2FDF), (0x20000, 0x3FFFF))


def _is_junk(c):
    """True if c is a bare stroke, a CHISE placeholder, or a non-CJK shape (katakana コ,
    ？) — the tell-tale signs that the IDS has over-decomposed a glyph to strokes or
    used an unencoded-component marker. A glyph whose breakdown contains any junk can't
    be trusted, so it is degraded rather than shown wrong."""
    if not c:
        return True
    o = ord(c)
    if 0x2460 <= o <= 0x24FF:         # circled numbers = CHISE unencoded placeholders
        return True
    if 0x31C0 <= o <= 0x31EF:         # CJK strokes block (㇀…㇟)
        return True
    if c in _STROKES:
        return True
    return not any(a <= o <= b for a, b in _GOOD_RANGES)  # non-CJK (katakana コ, ？…)


def _consume(s, i):
    """Return the end index of the one IDS node starting at i (recursive-descent)."""
    if i >= len(s):
        return i
    c = s[i]
    if c in _IDC_ARITY:
        i += 1
        for _ in range(_IDC_ARITY[c]):
            i = _consume(s, i)
        return i
    return i + 1


def _top_level(ids):
    """(root_idc_or_None, [direct operand substrings])."""
    if not ids:
        return None, []
    root = ids[0]
    if root not in _IDC_ARITY:
        return None, [ids]
    ops, i = [], 1
    for _ in range(_IDC_ARITY[root]):
        j = _consume(ids, i)
        ops.append(ids[i:j])
        i = j
    return root, ops


def _leaves(node):
    """Flatten a (possibly nested) IDS node to its atomic component characters."""
    if not node:
        return []
    if node[0] in _IDC_ARITY:
        _, ops = _top_level(node)
        out = []
        for o in ops:
            out.extend(_leaves(o))
        return out
    return [node]


