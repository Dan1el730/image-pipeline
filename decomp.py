@lru_cache(maxsize=4096)
def decompose(ch):
    """Deterministic 部件拆解 for a single character.

    Returns dict: components (list), semantic_radical, semantic_radical_name,
    semantic_meaning, semantic_domain, phonetic_radical, position, char_story,
    component_details.
    Falls back gracefully for 獨體 chars or chars absent from the database.
    """
    if _is_radical(ch):
        rad_info = get_radical_info(ch)
        story = get_char_story(ch, ch, "", [ch], "")
        return {
            "components": [ch],
            "semantic_radical": ch,
            "semantic_radical_name": rad_info.get("name", ch),
            "semantic_meaning": rad_info.get("meaning", ""),
            "semantic_domain": rad_info.get("domain", ""),
            "phonetic_radical": "無",
            "position": "獨體",
            "char_story": story,
            "component_details": [{
                "char": ch,
                "role": "whole",
                "label": "部首字",
                "name": rad_info.get("name", ch),
                "meaning": rad_info.get("meaning", ""),
                "domain": rad_info.get("domain", ""),
            }],
        }

    if ch in _CUSTOM_RADICAL:
        custom = _CUSTOM_RADICAL[ch]
        c_rad = custom["radical"]
        c_pos = custom.get("position", "")
        rad_info = get_radical_info(c_rad)
        story = get_char_story(ch, c_rad, "", [ch], "")
        return {
            "components": [ch],
            "semantic_radical": c_rad,
            "semantic_radical_name": rad_info.get("name", c_rad),
            "semantic_meaning": rad_info.get("meaning", ""),
            "semantic_domain": rad_info.get("domain", ""),
            "phonetic_radical": "無",
            "position": c_pos,
            "complex": True,
            "char_story": story,
            "component_details": [{
                "char": ch,
                "role": "whole",
                "label": "整字",
                "name": ch,
                "meaning": story,
                "domain": rad_info.get("domain", ""),
            }],
        }

    ids = _IDS.get(ch, "")
    if not ids or ids == ch or len(ids) == 1:
        is_rad = _is_radical(ch)
        rad_info = get_radical_info(ch) if is_rad else {}
        story = get_char_story(ch, ch if is_rad else "", "", [ch], "")
        return {
            "components": [ch],
            "semantic_radical": ch if is_rad else "",
            "semantic_radical_name": rad_info.get("name", ch if is_rad else ""),
            "semantic_meaning": rad_info.get("meaning", ""),
            "semantic_domain": rad_info.get("domain", ""),
            "phonetic_radical": "無",
            "position": "獨體",
            "char_story": story,
            "component_details": [{
                "char": ch,
                "role": "whole",
                "label": "獨體字" if not is_rad else "部首字",
                "name": rad_info.get("name", ch),
                "meaning": rad_info.get("meaning", ""),
                "domain": rad_info.get("domain", ""),
            }],
        }
    root, ops = _top_level(ids)
    # Collect candidate components.
    raw = []
    for op in ops:
        raw.extend([op] if len(op) == 1 else _leaves(op))
    # Junk anywhere in the breakdown (a bare stroke コ丨乛, a placeholder ⑦) means the IDS
    # has over-decomposed (慶) or used an unencoded-component marker (華) — the whole
    # breakdown is untrustworthy, not just the junk leaf. Degrade honestly: show the whole
    # char, claim no radical, rather than fabricate parts or a wrong 形旁. A real ext-B
    # component (𠂊, the top of 負) is NOT junk, so 負 keeps 𠂊、貝.
    if any(_is_junk(c) for c in raw) or len(raw) < 2:
        story = get_char_story(ch, "", "", [ch], root or "")
        return {
            "components": [ch],
            "semantic_radical": "",
            "semantic_radical_name": "",
            "semantic_meaning": "",
            "semantic_domain": "",
            "phonetic_radical": "無",
            "position": "",
            "complex": True,
            "char_story": story,
            "component_details": [{
                "char": ch,
                "role": "whole",
                "label": "整字",
                "name": ch,
                "meaning": story,
                "domain": "",
            }],
        }
    # Radical + its position come ONLY from a single-char DIRECT operand that is a Kangxi
    # radical; the other operand is the phonetic. No radical → no position (an empty 形旁
    # with a position would be misleading).
    radical, position, phonetic = "", "", ""
    for idx, op in enumerate(ops):
        if len(op) == 1:
            if _is_radical(op) and not radical:
                radical = op
                slot = _POS.get(root or "", [])
                position = slot[idx] if idx < len(slot) else ""
            elif not phonetic:
                phonetic = op
    if not radical:  # radical may sit inside a nested operand — find it, but don't guess position
        for lf in raw:
            if _is_radical(lf):
                radical = lf
                break

    rad_info = get_radical_info(radical) if radical else {}
    phon_info = get_component_info(phonetic) if (phonetic and phonetic != "無") else {}
    story = get_char_story(ch, radical, phonetic, raw, root or "")

    comp_details = []
    for c in raw:
        c_info = get_radical_info(c) if _is_radical(c) else get_component_info(c)
        if radical and (c == radical or _VARIANT.get(c, "") == radical or c == _VARIANT.get(radical, "")):
            role = "semantic"
            lab = "形旁（字義）"
        elif phonetic and c == phonetic:
            role = "phonetic"
            lab = "聲旁（字音）"
        elif _is_radical(c):
            role = "ideographic"
            lab = "會意部件"
        else:
            role = "component"
            lab = "部件"
        comp_details.append({
            "char": c,
            "role": role,
            "label": lab,
            "name": c_info.get("name", c),
            "meaning": c_info.get("meaning", ""),
            "domain": c_info.get("domain", ""),
        })

    return {
        "components": raw,
        "semantic_radical": radical,
        "semantic_radical_name": rad_info.get("name", radical),
        "semantic_meaning": rad_info.get("meaning", ""),
        "semantic_domain": rad_info.get("domain", ""),
        "phonetic_radical": phonetic or "無",
        "phonetic_name": phon_info.get("name", phonetic),
        "position": position,
        "char_story": story,
        "component_details": comp_details,
    }


def _phonetic_of(ch):
    d = decompose(ch)
    p = d.get("phonetic_radical", "")
    return p if p and p != "無" and len(p) == 1 else ""


# component -> chars that carry it as a direct top-level operand (for 形近字 lookup)
_COMP_INDEX = None


def _build_index():
    global _COMP_INDEX
    if _COMP_INDEX is not None:
        return
    _COMP_INDEX = {}
    for ch, ids in _IDS.items():
        _, ops = _top_level(ids)
        for op in ops:
            if len(op) == 1:
                _COMP_INDEX.setdefault(op, set()).add(ch)


def confusables(ch, k=3):
    """Real visually-similar characters, drawn from three genuine 形近 signals:
      1. chars sharing this char's phonetic component  (形聲 family — 模/摸/膜/漠)
      2. chars that CONTAIN this char as a component   (rescues chars like 危 → 脆/跪,
         which are themselves phonetics rather than having a rich phonetic family)
      3. fallback: chars sharing the radical in the same structure
    Simplified glyphs are dropped (Traditional-only) and the result is ranked toward
    P4-common characters so the contrast is one the child has actually met."""
    _build_index()
    if ch not in _IDS:
        return []
    root, _ = _top_level(_IDS[ch])
    phon = _phonetic_of(ch)
    # Primary pool (1)+(2) — genuine 形近: shares the phonetic, or contains the target.
    primary = set((_COMP_INDEX or {}).get(phon, set())) if phon else set()
    primary |= set((_COMP_INDEX or {}).get(ch, set()))
    primary = {c for c in primary if c != ch and not _is_simplified(c)}
    # Fallback pool (3) — same radical + structure. A WEAKER 形近 (the distinctive part
    # differs a lot), so it is tiered strictly below primary and never displaces it.
    # Only computed when the primary family is too thin to fill k slots.
    fallback = set()
    if len(primary) < k:
        rad = decompose(ch).get("semantic_radical", "")
        if rad:
            for c in (_COMP_INDEX or {}).get(rad, set()):
                if c != ch and c not in primary and not _is_simplified(c) \
                        and _top_level(_IDS.get(c, ""))[0] == root:
                    fallback.add(c)
    tier = {c: 0 for c in primary}
    tier.update({c: 1 for c in fallback})
    # rank: primary tier first, then most common (a P4 child must recognise it), then
    # same structure as the target, then shorter IDS as a final tiebreak.
    ranked = sorted(
        primary | fallback,
        key=lambda c: (
            tier[c],
            _FREQ.get(c, _RARE),
            _top_level(_IDS.get(c, ""))[0] != root,
            len(_IDS.get(c, "")),
        ),
    )
    return ranked[:k]


def contrast(ch, confs):
    """Factual 辨析 line for the confusable set."""
    phon = _phonetic_of(ch)
    if confs and phon:
        return f"「{ch}」與「{'、'.join(confs)}」同含部件「{phon}」，字形相近；分辨重點在其餘部件（部首）的不同。"
    if confs:
        return f"「{ch}」與「{'、'.join(confs)}」字形相近，注意部件的細微分別。"
    return "（資料庫中未找到合適的形近字。）"
